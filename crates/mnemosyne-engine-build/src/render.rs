fn interactivity(chunks: &mut Chunks, layer: &Interactivity) -> String {
    let mut ladders: Vec<(String, Vec<Rung>)> = layer
        .ladders
        .iter()
        .map(|(section, rungs)| (section.clone(), rungs.clone()))
        .collect();
    ladders.sort_by(|a, b| a.0.cmp(&b.0));
    let mut objects: Vec<String> = layer.objects.iter().cloned().collect();
    objects.sort();
    let ladders = chunked(
        chunks,
        SECTION_RUNGS_TY,
        &ladders,
        |chunks, (section, rungs)| {
            let rungs = chunked(chunks, RUNG_TY, rungs, |_, r| rung(r));
            format!("({}, {})", string(section), rungs)
        },
    );
    let objects = strings(chunks, &objects);
    format!(
        "::mnemosyne_engine::Interactivity {{ ladders: {ladders}.into_iter().collect(), \
         objects: {objects}.into_iter().collect(), free_investigate: {} }}",
        layer.free_investigate,
    )
}

fn rung(r: &Rung) -> String {
    format!(
        "::mnemosyne_engine::Rung {{ question: {}, question_anchor: {}, reveals: {}, needs: {} }}",
        string(&r.question),
        option(r.question_anchor.as_ref().map(anchor)),
        string(&r.reveals),
        inline_strings(&r.needs),
    )
}

/// Render a baked passage set as Rust source (Round 791) — the third emitter,
/// and the third to end in [`artifact`], so the composition rule and the
/// `&'static` handle hold on this axis without being re-derived.
///
/// Deterministic for the same reason the other two are: [`passages_to_parts`]
/// sorts by section id, so the same store emits byte-identical source.
///
/// # Why the passage set is chunked at all
///
/// Round 789 measured this axis before it was shaped, and found the opposite of
/// what both sides expected. Prose is FEW and LONG — 56 spots of ~2,655
/// characters in the first consumer's store — so the emitted longest line is
/// enormous (319 KB) and costs nothing: rustc charges per ITEM, and the whole
/// 1.43 MB artifact compiles in 0.05s against 2.47s for a line artifact of
/// nearly the same bytes in 4,612 items. [`CHUNK`] is therefore already the
/// right bound here, unchanged, and the Round 775 regression test passes because
/// it asserts a RATIO rather than a byte threshold. Nothing about this emitter
/// needed a special case; the measurement is what established that.
pub fn render_passages(parts: &PassagesParts) -> String {
    let mut c = Chunks::new();
    let entries = chunked(&mut c, PASSAGE_ENTRY_TY, &parts.passages, |_, (id, p)| {
        format!(
            "({}, ::mnemosyne_engine::PassagePart {{ anchor: {}, text: ::std::borrow::Cow::Borrowed({}) }})",
            string(id),
            anchor(&p.anchor),
            str_literal(&p.text)
        )
    });
    let mut build = String::new();
    build.push_str("    ::mnemosyne_engine::passages_from_parts(\n");
    build.push_str("        ::mnemosyne_engine::PassagesParts {\n");
    let _ = writeln!(build, "            passages: {entries},");
    build.push_str("        },\n    )\n");
    artifact(PASSAGES_FN_NAME, PASSAGES_TY, &c, &build)
}

/// One baked passage entry, as generated Rust.
const PASSAGE_ENTRY_TY: &str = "(::std::string::String, ::mnemosyne_engine::PassagePart)";

fn anchor(a: &ContentAnchor) -> String {
    let locator = match &a.locator {
        Locator::Prefix(p) => format!("::mnemosyne_engine::Locator::Prefix({})", string(p)),
        Locator::Cfi(c) => format!("::mnemosyne_engine::Locator::Cfi({})", string(c)),
    };
    format!(
        "::mnemosyne_engine::ContentAnchor {{ source: {}, locator: {locator} }}",
        string(&a.source)
    )
}

fn disclosure_mode(mode: mnemosyne_engine::DisclosureMode) -> String {
    let variant = match mode {
        mnemosyne_engine::DisclosureMode::Withhold => "Withhold",
        mnemosyne_engine::DisclosureMode::State => "State",
        mnemosyne_engine::DisclosureMode::Hint => "Hint",
        mnemosyne_engine::DisclosureMode::Imply => "Imply",
    };
    format!("::mnemosyne_engine::DisclosureMode::{variant}")
}

fn modality(modality: mnemosyne_engine::Modality) -> String {
    let variant = match modality {
        mnemosyne_engine::Modality::Observed => "Observed",
        mnemosyne_engine::Modality::Guessed => "Guessed",
        mnemosyne_engine::Modality::Told => "Told",
        mnemosyne_engine::Modality::Remembered => "Remembered",
    };
    format!("::mnemosyne_engine::Modality::{variant}")
}
